import type { AxiosError, AxiosInstance, AxiosRequestConfig } from "axios";
import { RateLimitError, APIConnectionError, TimeoutError } from "../errors/index.js";
import { calculateBackoff, delay, noopLogger } from "../utils/index.js";
import type { RetryConfig, Logger } from "../types/index.js";
import { AuthenticationError, MpesaAPIError } from "../errors/index.js";

const DEFAULT_RETRY_CONFIG: RetryConfig = {
  maxRetries: 3,
  baseDelayMs: 1000,
  maxDelayMs: 30000,
};

const RETRYABLE_STATUS_CODES = new Set([408, 429, 500, 502, 503, 504]);
// Transport-level failures Node can report for a request that never produced a
// response. Deliberately an allow-list: an unlisted code is simply not retried,
// and `ERR_CANCELED` (a caller aborting) must never be retried.
const RETRYABLE_ERROR_CODES = new Set([
  "ECONNABORTED",
  "ECONNREFUSED",
  "ECONNRESET",
  "EHOSTUNREACH",
  "ENETUNREACH",
  "ENOTFOUND",
  "EPIPE",
  "ETIMEDOUT",
  "EAI_AGAIN",
  "ERR_NETWORK",
]);

const IDEMPOTENT_METHODS = new Set(["GET", "HEAD", "OPTIONS"]);
const IDEMPOTENCY_KEY_HEADER = "x-idempotency-key";

/**
 * The idempotency key of a dispatched request, if it carries one.
 *
 * Axios replaces `config.headers` with an `AxiosHeaders` instance while
 * dispatching, so both that shape and a plain object are accepted.
 */
function idempotencyKeyOf(config: AxiosRequestConfig): string | undefined {
  const headers = config.headers as
    | (Record<string, unknown> & { get?: (name: string) => unknown })
    | undefined;
  if (!headers) return undefined;

  if (typeof headers.get === "function") {
    const value = headers.get(IDEMPOTENCY_KEY_HEADER);
    if (value !== undefined && value !== null) return String(value);
  }

  for (const [name, value] of Object.entries(headers)) {
    if (name.toLowerCase() === IDEMPOTENCY_KEY_HEADER && value !== undefined && value !== null) {
      return String(value);
    }
  }
  return undefined;
}

/**
 * Whether a request may be retried at all.
 *
 * `GET`/`HEAD`/`OPTIONS` are safe to replay. Payment traffic is `POST`, which is
 * only replayed when the request carries a non-empty `X-Idempotency-Key`: either
 * generated by the client (idempotency enabled) or supplied by the caller. A
 * POST without a key is attempted once, so an unexpected failure can never
 * duplicate a payment.
 */
function isReplayable(config: AxiosRequestConfig): boolean {
  const method = (config.method || "").toUpperCase();
  if (IDEMPOTENT_METHODS.has(method)) return true;
  if (method !== "POST") return false;

  const key = idempotencyKeyOf(config);
  return typeof key === "string" && key.trim() !== "";
}

export function setupRetryInterceptor(
  client: AxiosInstance,
  retryConfig: RetryConfig = DEFAULT_RETRY_CONFIG,
  logger: Logger = noopLogger,
): void {
  client.interceptors.response.use(
    (response) => response,
    async (error: AxiosError) => {
      const config = error.config;
      if (!config) return Promise.reject(error);

      const attempt = (config.retryCount ?? 0) + 1;
      const requestId = (config.headers?.["X-Request-ID"] as string) ?? "";

      if (attempt > retryConfig.maxRetries) {
        logger.warn("Max retries exceeded", {
          url: config.url,
          attempt: attempt - 1,
          maxRetries: retryConfig.maxRetries,
          requestId,
        });
        return Promise.reject(error);
      }

      const shouldRetry =
        (RETRYABLE_STATUS_CODES.has(error.response?.status ?? 0) ||
          RETRYABLE_ERROR_CODES.has(error.code ?? "")) &&
        isReplayable(config);

      if (!shouldRetry) {
        return Promise.reject(error);
      }

      config.retryCount = attempt;

      logger.warn("Retrying request after error", {
        url: config.url,
        status: error.response?.status,
        code: error.code,
        attempt,
        maxRetries: retryConfig.maxRetries,
        requestId,
      });

      if (error.response?.status === 429) {
        const retryAfter = parseInt(
          error.response.headers["retry-after"] ?? "5",
          10,
        );
        logger.warn("Rate limited, backing off", { retryAfter, requestId });
        await delay(retryAfter * 1000);
      } else {
        const backoff = calculateBackoff(
          attempt - 1,
          retryConfig.baseDelayMs,
          retryConfig.maxDelayMs,
        );
        logger.warn("Backing off before retry", {
          backoffMs: backoff,
          attempt,
          requestId,
        });
        await delay(backoff);
      }

      return client.request(config);
    },
  );
}

export function mapAxiosError(error: AxiosError): Error {
  const status = error.response?.status;
  const data = error.response?.data as Record<string, unknown> | undefined;
  const requestId = (data?.requestId as string) ?? error.config?.headers?.["X-Request-Id"] as string;

  if (error.code === "ECONNABORTED" || error.code === "ETIMEDOUT") {
    return new TimeoutError("Request to M-Pesa API timed out.", {
      statusCode: status,
      requestId,
      rawResponse: data,
      cause: error,
    });
  }

  if (
    error.code === "ECONNREFUSED" ||
    error.code === "ENOTFOUND" ||
    error.code === "ERR_NETWORK"
  ) {
    return new APIConnectionError("Failed to connect to M-Pesa API.", {
      statusCode: status,
      requestId,
      rawResponse: data,
      cause: error,
    });
  }

  if (status === 429) {
    const retryAfter = parseInt(
      error.response?.headers?.["retry-after"] as string ?? "60",
      10,
    );
    return new RateLimitError("M-Pesa API rate limit exceeded.", {
      statusCode: status,
      requestId,
      rawResponse: data,
      retryAfter,
      cause: error,
    });
  }

  if (status === 401) {
    return new AuthenticationError(
      "M-Pesa API authentication failed. Check your consumer key/secret.",
      { statusCode: status, requestId, rawResponse: data, cause: error },
    );
  }

  return new MpesaAPIError(
    (data?.errorMessage as string) ?? error.message,
    {
      statusCode: status,
      errorCode: data?.errorCode as string,
      requestId,
      rawResponse: data,
      cause: error,
    },
  );
}
