"""Regression: `OriginatorConversationID` is optional for B2C/B2Pochi (docs + TS parity).

`OriginatorConversationID` is documented as optional and auto-generated by
M-Pesa when omitted (see ``docs/apis/b2c.md`` and ``docs/apis/business-to-pochi.md``).
These tests pin that contract and the wire behavior: the field is omitted when
absent and forwarded verbatim when supplied.
"""

from __future__ import annotations

from unittest.mock import patch

from daraja import Mpesa

_RESPONSE = {
    "OriginatorConversationID": "oci-1",
    "ConversationID": "ci-1",
    "ResponseCode": "0",
    "ResponseDescription": "Success",
}

_B2C_BASE = {
    "CommandID": "BusinessPayment",
    "Amount": 100,
    "PartyA": 600998,
    "PartyB": 254722000000,
    "Remarks": "test",
    "Occasion": "",
    "QueueTimeOutURL": "https://example.com/timeout",
    "ResultURL": "https://example.com/result",
}


def _client() -> Mpesa:
    return Mpesa(
        {
            "consumer_key": "k",
            "consumer_secret": "s",
            "security_credential": "sc",
            "initiator_name": "init",
        }
    )


def test_b2c_omits_originator_conversation_id_when_absent() -> None:
    client = _client()
    with patch.object(client, "_post", return_value=_RESPONSE) as mock_post:
        client.b2c(dict(_B2C_BASE))
        body = mock_post.call_args[0][1]
        assert "OriginatorConversationID" not in body
    client.close()


def test_b2c_forwards_originator_conversation_id_when_provided() -> None:
    client = _client()
    with patch.object(client, "_post", return_value=_RESPONSE) as mock_post:
        client.b2c({**_B2C_BASE, "OriginatorConversationID": "my-id"})
        body = mock_post.call_args[0][1]
        assert body["OriginatorConversationID"] == "my-id"
    client.close()


def test_b2pochi_omits_originator_conversation_id_when_absent() -> None:
    client = _client()
    with patch.object(client, "_post", return_value=_RESPONSE) as mock_post:
        client.b2pochi(
            {
                "CommandID": "BusinessPayToPochi",
                "Amount": 100,
                "PartyA": 600998,
                "PartyB": 254722000000,
                "Remarks": "test",
                "QueueTimeOutURL": "https://example.com/timeout",
                "ResultURL": "https://example.com/result",
            }
        )
        body = mock_post.call_args[0][1]
        assert "OriginatorConversationID" not in body
    client.close()
